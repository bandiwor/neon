//! Translation of the IR to C: one self-contained, `static`-only source file.
//!
//! The file is laid out as: includes, runtime declarations (macros, types, prototypes), the
//! program's declarations, the program's functions, `main`, and finally the runtime
//! implementation. Only what the program uses is emitted — runtime functions are pulled in one by one
//! through their dependencies (see [`rt`]).

mod emit;
mod rt;
mod rt_core;
mod rt_data;
mod rt_fmt;

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::ir::IrProgram;
use emit::{c_string, Gen};
use rt::Kind;

/// Translates `prog` to C. Fails only for programs outside what the backend supports (a struct with
/// more than 64 fields).
pub fn emit_c(prog: &IrProgram) -> Result<String, String> {
    let (out, mut needs, sys) = Gen::new(prog).generate()?;
    needs.always.insert("hdr_stdio".to_string());
    if !out.strs.is_empty() {
        needs.always.insert("str_new".to_string());
    }
    // what a release build needs, and what only a checked build adds on top
    let release = rt::closure(&needs.always);
    let pieces = rt::closure(&needs.always.union(&needs.checked).cloned().collect());
    let with_gc = pieces.contains("gc_collect");
    // a piece (or function) outside the release set sits in `#if NEON_CHECKS`
    let guarded = |name: &str, text: &str| -> String {
        if release.contains(name) {
            text.to_string()
        } else {
            format!("#if NEON_CHECKS\n{text}\n#endif")
        }
    };

    let all = rt::all();
    let chosen: Vec<&rt::Piece> = all.iter().copied().filter(|p| pieces.contains(p.name)).collect();

    let mut hdrs: BTreeSet<&str> = ["stddef.h", "stdint.h"].into_iter().collect();
    for p in &chosen {
        hdrs.extend(p.hdrs.iter().copied());
    }

    let mut s = String::new();
    s.push_str("/* Generated by the Neon compiler. One self-contained C99 file; every function is static.\n");
    s.push_str(
        " * Build: cc -O2 program.c -o program -lm      (-DNDEBUG: release, no arithmetic traps or recursion guard; -DNEON_MAX_DEPTH=n) */\n\n",
    );
    // include order: the usual one, not alphabetical
    for h in ["stddef.h", "stdint.h", "stdarg.h", "stdio.h", "stdlib.h", "string.h", "math.h"] {
        if hdrs.remove(h) {
            let _ = writeln!(s, "#include <{h}>");
        }
    }
    for h in hdrs {
        let _ = writeln!(s, "#include <{h}>");
    }

    // ---- runtime declarations ----------------------------------------------------------------
    section(&mut s, "Runtime: declarations");
    for p in chosen.iter().filter(|p| p.kind == Kind::Decl && !p.src.is_empty()) {
        s.push_str(&guarded(p.name, p.src));
        s.push_str("\n\n");
    }
    for p in chosen.iter().filter(|p| p.kind == Kind::Funcs) {
        let protos = rt::prototypes(p.src).join("\n");
        s.push_str(&guarded(p.name, &protos));
        s.push('\n');
    }
    for (name, (src, in_release)) in &sys {
        let protos = rt::prototypes(src).join("\n");
        s.push_str(&if *in_release || release.contains(name.as_str()) {
            protos
        } else {
            format!("#if NEON_CHECKS\n{protos}\n#endif")
        });
        s.push('\n');
    }

    // ---- program declarations -----------------------------------------------------------------
    section(&mut s, "Program: declarations");
    for t in &out.typedefs {
        let _ = writeln!(s, "{t}");
    }
    for g in &out.globals {
        let _ = writeln!(s, "{g}");
    }
    if !out.strs.is_empty() {
        let _ = writeln!(s, "static const struct {{ const char *s; size_t n; }} k_lit[{}] = {{", out.strs.len());
        for &i in &out.strs {
            let text = &prog.strings[i as usize];
            let _ = writeln!(s, "    {{{}, {}}},", c_string(text), text.len());
        }
        s.push_str("};\n");
        let _ = writeln!(s, "static Obj *k_str[{}];   /* string constants, created on first use */", out.strs.len());
        s.push_str("static Obj *kstr(int i);\n");
    }
    for p in &out.fn_protos {
        let _ = writeln!(s, "{p}");
    }

    // ---- program -----------------------------------------------------------------------------------
    section(&mut s, "Program");
    if !out.strs.is_empty() {
        s.push_str("static Obj *kstr(int i) {\n    if (UNLIKELY(k_str[i] == NULL)) k_str[i] = str_new(k_lit[i].s, k_lit[i].n);\n    return k_str[i];\n}\n\n");
    }
    if with_gc {
        s.push_str("/* The collector's roots besides the frames: globals and string constants. */\nstatic void user_roots(void) {\n");
        for g in &out.ref_globals {
            let _ = writeln!(s, "    gc_mark({g});");
        }
        if !out.strs.is_empty() {
            let _ = writeln!(
                s,
                "    {{\n        int i;\n        for (i = 0; i < {}; i++) gc_mark(k_str[i]);\n    }}",
                out.strs.len()
            );
        }
        s.push_str("}\n\n");
    }
    for b in &out.fn_bodies {
        s.push_str(b);
        s.push_str("\n\n");
    }

    // ---- main ------------------------------------------------------------------------------------------
    section(&mut s, "Entry point");
    if pieces.contains("rt_args") {
        let _ = writeln!(
            s,
            "int main(int argc, char **argv) {{\n    rt_argc = argc;\n    rt_argv = argv;\n    {}();\n    fflush(stdout);\n    return 0;\n}}\n",
            out.entry
        );
    } else {
        let _ = writeln!(s, "int main(void) {{\n    {}();\n    fflush(stdout);\n    return 0;\n}}\n", out.entry);
    }

    // ---- runtime implementation ------------------------------------------------------------------------
    section(&mut s, "Runtime: implementation");
    for p in chosen.iter().filter(|p| p.kind == Kind::Funcs) {
        s.push_str(&guarded(p.name, p.src));
        s.push_str("\n\n");
    }
    for (src, in_release) in sys.values() {
        s.push_str(&if *in_release { src.clone() } else { format!("#if NEON_CHECKS\n{src}\n#endif") });
        s.push_str("\n\n");
    }
    while s.ends_with("\n\n") {
        s.pop();
    }
    Ok(s)
}

fn section(s: &mut String, title: &str) {
    let _ = write!(s, "\n/* ---- {title} {}*/\n\n", "-".repeat(70usize.saturating_sub(title.len())));
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::driver::{compile_source, Options};
    use crate::vfs::MemVfs;

    fn c_of(src: &str) -> String {
        let c = compile_source("t.neon", src, &MemVfs::new(), &Options::default());
        assert!(!c.diags.has_errors(), "{}", c.render_diagnostics());
        emit_c(c.ir.as_ref().unwrap()).unwrap()
    }

    #[test]
    fn the_runtime_registry_is_consistent() {
        let all = rt::all();
        let mut names = BTreeSet::new();
        for p in &all {
            assert!(names.insert(p.name), "duplicate piece {}", p.name);
        }
        for p in &all {
            for d in p.deps {
                assert!(names.contains(d), "{} depends on the unknown piece {d}", p.name);
                // declarations a piece needs come before it, so the file compiles in order
                let (di, pi) = (all.iter().position(|q| q.name == *d), all.iter().position(|q| q.name == p.name));
                if all[di.unwrap()].kind == Kind::Decl {
                    assert!(di < pi, "{} is declared after {}", d, p.name);
                }
            }
            if p.kind == Kind::Funcs {
                // every top-level definition is static and gets a prototype
                let defs = p.src.lines().filter(|l| l.ends_with(") {") && !l.starts_with(' ')).count();
                assert!(
                    defs >= 1 && rt::prototypes(p.src).len() == defs,
                    "{}: definitions need one-line `static` headers",
                    p.name
                );
                assert!(!p.src.contains("inline"), "{}", p.name);
            }
        }
    }

    #[test]
    fn the_closure_follows_dependencies_once() {
        let need: BTreeSet<String> = ["str_substring".to_string()].into();
        let got = rt::closure(&need);
        for d in ["str_new", "obj_new", "heapstate", "trap_index", "rt_fail", "utf8_skip"] {
            assert!(got.contains(d), "{d} missing from {got:?}");
        }
        assert!(!got.contains("gc_collect"));
    }

    #[test]
    fn prototypes_come_from_the_headers() {
        let src = "/* c */\nstatic int f(int a) {\n    return a;\n}\nstatic NORETURN void g(void) {\n    for (;;) {\n    }\n}";
        assert_eq!(rt::prototypes(src), ["static int f(int a);", "static NORETURN void g(void);"]);
    }

    #[test]
    fn c_strings_are_escaped() {
        assert_eq!(c_string("a\"b\\c\n?"), "\"a\\\"b\\\\c\\n\\?\"");
        assert_eq!(c_string("é"), "\"\\303\\251\"");
    }

    #[test]
    fn only_what_the_program_uses_is_emitted() {
        let tiny = c_of("println(1 + 2);");
        assert!(tiny.contains("out_sb") && !tiny.contains("gc_collect") && !tiny.contains("map_put"));
        let heavy = c_of("var a = [3, 1, 2]; a.sort(); var m = { \"k\": 1 }; println(a); println(m);");
        for name in ["gc_collect", "arr_sort", "map_put", "cmp_s64", "user_roots"] {
            assert!(heavy.contains(name), "{name}");
        }
        assert!(!heavy.contains("fmt_value") && !heavy.contains("str_split"));
    }

    #[test]
    fn functions_are_static_and_ordered() {
        let c = c_of("fn sq(x: i64) -> i64 { x * x } fn main() { println(sq(7)); }");
        assert!(c.contains("static ") && !c.contains("inline"));
        let main_at = c.find("int main(void)").unwrap();
        let user_at = c.find("n_start").unwrap();
        let rt_impl = c.find("Runtime: implementation").unwrap();
        assert!(user_at < main_at && main_at < rt_impl);
        // the runtime's declarations precede the program's
        assert!(c.find("Runtime: declarations").unwrap() < c.find("Program: declarations").unwrap());
    }

    #[test]
    fn checks_sit_behind_one_macro() {
        let c = c_of(
            "fn main() { let a = input().parse_i64(); let b = input().parse_i64(); println(a * b); println(a << b); }",
        );
        assert!(c.contains("#ifndef NEON_CHECKS") && c.contains("#ifdef NDEBUG"));
        // the traps and the overflow macros are compiled out together with their only users
        let trap = c.find("#if NEON_CHECKS\nstatic NORETURN COLD void trap_overflow").unwrap();
        assert!(trap < c.find("Program: declarations").unwrap());
        assert!(
            c.contains("#if NEON_CHECKS\n    int64_t r;") && c.contains("return (int64_t)((uint64_t)a * (uint64_t)b);")
        );
        let rec = c_of("fn f(n: i64) -> i64 { if n == 0 { 0 } else { 1 + f(n - 1) } } fn main() { println(f(5)); }");
        assert!(
            rec.contains("DEPTH_ENTER();")
                && rec.contains("DEPTH_LEAVE();")
                && rec.contains("#define DEPTH_ENTER() ((void)0)")
        );
    }

    #[test]
    fn closures_get_cells_and_a_collector_frame() {
        let c = c_of(
            "fn make() -> fn() -> i64 { var n = 0; || => { n += 1; n } } fn main() { let f = make(); println(f()); println(f()); }",
        );
        assert!(c.contains("cell_new") && c.contains("clo_new") && c.contains("CELL(up[0])->v"));
        assert!(c.contains("Frame fr") && c.contains("GC_POINT();"));
    }

    #[test]
    fn recursion_is_guarded_and_plain_code_is_not() {
        let c = c_of("fn f(n: i64) -> i64 { if n == 0 { 0 } else { 1 + f(n - 1) } } fn main() { println(f(5)); }");
        assert!(c.contains("++rt_depth > NEON_MAX_DEPTH"));
        let d = c_of("fn main() { let x = 3.0; println(x * x + 1.0); }");
        assert!(!d.contains("rt_depth"));
    }

    #[test]
    fn structs_with_too_many_fields_are_reported() {
        let fields: String = (0..70).map(|i| format!("x{i}: i64, ")).collect();
        let vals: String = (0..70).map(|i| format!("x{i}: {i}, ")).collect();
        let src = format!("struct Big {{ {fields} }} fn main() {{ let b = Big {{ {vals} }}; println(b.x3); }}");
        let c = compile_source(
            "t.neon",
            &src,
            &MemVfs::new(),
            &Options { opt: crate::ir::OptConfig::none(), ..Options::default() },
        );
        assert!(!c.diags.has_errors(), "{}", c.render_diagnostics());
        let err = emit_c(c.ir.as_ref().unwrap()).unwrap_err();
        assert!(err.contains("64 fields"), "{err}");
    }
}
