// Types for the CSS modules: next to every `Foo.module.scss` a `Foo.module.d.scss.ts` that lists its classes,
// so `styles.rowMain` is checked and a typo is a compile error. The classes are what Lightning CSS exports for
// the compiled Sass, i.e. exactly what the bundle will contain.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import * as sass from 'sass';
import { transform } from 'lightningcss';
import type { Plugin } from 'vite';

export function declarationPath(scss: string): string {
  return scss.replace(/\.scss$/, '.d.scss.ts');
}

/** The local class names a stylesheet defines. */
export function classesOf(scss: string, loadPaths: readonly string[]): string[] {
  const css = sass.compile(scss, { loadPaths: [...loadPaths], silenceDeprecations: ['import'] }).css;
  const { exports } = transform({ filename: scss, code: Buffer.from(css), cssModules: true, minify: false });
  return Object.keys(exports ?? {}).sort();
}

export function declarationFor(names: readonly string[]): string {
  const fields = names.map((n) => `  readonly ${/^[A-Za-z_$][\w$]*$/.test(n) ? n : JSON.stringify(n)}: string;`);
  return [
    '// Generated by build/plugins/cssModuleTypes.ts from the stylesheet. Do not edit; it is not committed.',
    'declare const classes: {',
    ...fields,
    '};',
    'export default classes;',
    '',
  ].join('\n');
}

function findModules(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return findModules(path);
    return name.endsWith('.module.scss') ? [path] : [];
  });
}

/** Writes the declaration if it changed; returns whether it did. */
export function writeDeclaration(scss: string, loadPaths: readonly string[]): boolean {
  const out = declarationPath(scss);
  const text = declarationFor(classesOf(scss, loadPaths));
  let old = '';
  try {
    old = readFileSync(out, 'utf8');
  } catch {
    /* new */
  }
  if (old === text) return false;
  writeFileSync(out, text);
  return true;
}

export function writeAllDeclarations(srcDir: string, loadPaths: readonly string[]): number {
  return findModules(srcDir).filter((f) => writeDeclaration(f, loadPaths)).length;
}

export interface CssModuleTypesOptions {
  readonly srcDir: string;
  readonly loadPaths: readonly string[];
}

export function cssModuleTypes({ srcDir, loadPaths }: CssModuleTypesOptions): Plugin {
  const src = resolve(srcDir);
  return {
    name: 'neon:css-module-types',
    buildStart() {
      writeAllDeclarations(src, loadPaths);
    },
    // a stylesheet was edited in dev: its types follow
    handleHotUpdate({ file, server }) {
      if (file.endsWith('.module.scss') && file.startsWith(src + '/')) {
        try {
          writeDeclaration(file, loadPaths);
        } catch (e) {
          server.config.logger.warn(`${dirname(file)}: ${e instanceof Error ? e.message : String(e)}`);
        }
      }
      return undefined;
    },
  };
}
